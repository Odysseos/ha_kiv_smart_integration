"""Generate YaHA configuration from actual registry entity IDs."""
import os
from pathlib import Path
import tempfile

import yaml

from homeassistant.helpers import area_registry as ar, device_registry as dr, entity_registry as er
from homeassistant.exceptions import ServiceValidationError

from .const import DOMAIN


def entity_config(cover, selection, temperature, humidity):
    return {
        cover: {
            "name": "Приточный клапан", "type": "ventilation",
            "state_template": "{{ {'open': 'on', 'closed': 'off'}.get(states('" + cover + "'), 'unavailable') }}",
            "turn_on": {"action": "select.select_option", "target": {"entity_id": selection}, "data": {"option": "Полное"}},
            "turn_off": {"action": "select.select_option", "target": {"entity_id": selection}, "data": {"option": "Нет"}},
            "modes": {"program": {"auto": "Авто", "low": "Малое", "medium": "Среднее", "high": "Большое", "max": "Полное"}},
            "custom_modes": {"program": {
                "state_template": "{{ 'off' if is_state('" + cover + "', 'closed') else states('" + selection + "') }}",
                "set_mode": {"action": "select.select_option", "target": {"entity_id": selection}, "data": {"option": "{{ mode }}"}},
            }},
            "custom_ranges": {"open": False},
            "properties": [{"type": "temperature", "entity": temperature}, {"type": "humidity", "entity": humidity}],
        }
    }


def config_for_device(hass, device_id):
    device = dr.async_get(hass).async_get(device_id)
    if device is None:
        raise ServiceValidationError("Unknown device")
    entries = [e for e in hass.config_entries.async_entries(DOMAIN) if e.entry_id in device.config_entries]
    if len(entries) != 1:
        raise ServiceValidationError("Choose a Vakio KIV Local device")
    entry = entries[0]
    ids = _entity_ids(hass, entry)
    return {
        "yandex_smart_home": {"entity_config": entity_config(**ids)},
        "filter_hint": {"include_entities": [ids["cover"]]},
    }


EXPORT_PATH = "includes/yandex_smart_home_vakio.yaml"
_EXPORT_HEADER = "# Generated by Vakio KIV Local: export_yaha_config\n"


def _entity_ids(hass, entry):
    registry = er.async_get(hass)
    ids = {}
    for key, platform in (("cover", "cover"), ("selection", "select"), ("temperature", "sensor"), ("humidity", "sensor")):
        entity_id = registry.async_get_entity_id(platform, DOMAIN, f"{entry.entry_id}_{key}")
        if entity_id is None or registry.async_get(entity_id).disabled:
            raise ServiceValidationError("Enable all four entities before generating the YaHA configuration")
        ids[key] = entity_id
    return ids


def config_for_all_devices(hass):
    """Build one entity_config mapping using registry identities and areas."""
    devices = dr.async_get(hass)
    areas = ar.async_get(hass)
    registry = er.async_get(hass)
    result = {}
    for entry in sorted(hass.config_entries.async_entries(DOMAIN), key=lambda item: item.entry_id):
        try:
            ids = _entity_ids(hass, entry)
        except ServiceValidationError as error:
            raise ServiceValidationError(f"{entry.title}: {error}") from error
        config = entity_config(**ids)[ids["cover"]]
        entity = registry.async_get(ids["cover"])
        device = devices.async_get(entity.device_id) if entity.device_id else None
        config["name"] = ((device.name_by_user or device.name) if device else None) or entry.title
        area_id = entity.area_id or (device.area_id if device else None)
        area = areas.async_get_area(area_id) if area_id else None
        if area:
            config["room"] = area.name
        result[ids["cover"]] = config
    return dict(sorted(result.items()))


def _write_export(path, contents):
    """Replace only an owned generated file, keeping the old file on failure."""
    path = Path(path)
    if path.exists() and not path.read_text(encoding="utf-8").startswith(_EXPORT_HEADER):
        raise ServiceValidationError(
            f"Refusing to replace {EXPORT_PATH}: it is not a Vakio KIV Local generated file. "
            "Move your existing configuration to another file first.")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent,
                                         prefix=".vakio_kiv_local-", suffix=".tmp", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(contents)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


async def async_export_config(hass):
    """Generate all devices before touching the output file."""
    config = config_for_all_devices(hass)
    document = {"filter": {"include_entities": list(config)}, "entity_config": config}
    contents = _EXPORT_HEADER + yaml.safe_dump(document, allow_unicode=True, sort_keys=False)
    try:
        await hass.async_add_executor_job(_write_export, hass.config.path(EXPORT_PATH), contents)
    except (OSError, UnicodeError) as error:
        raise ServiceValidationError(f"Could not save {EXPORT_PATH}: {error}") from error
    return {
        "file": EXPORT_PATH,
        "device_count": len(config),
        "filter_hint": {"include_entities": list(config)},
    }
